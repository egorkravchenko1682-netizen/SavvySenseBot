"""
Группы регионов SAVVY SENSE.

Значения регионов — двухбуквенные коды из README ("Поддерживаемые
регионы"), плюс "CN" (Китай) и "WORLD" (весь остальной мир) для
поиска за пределами СНГ.
"""

# Евразийский экономический союз. Внутри союза — свободное перемещение
# товаров (без таможенных пошлин при провозе физлицом для личных нужд).
EAEU_REGIONS = {"BY", "RU", "KZ", "AM", "KG"}

# Все страны СНГ, поддерживаемые ботом (см. README).
CIS_REGIONS = {"BY", "RU", "KZ", "UZ", "KG", "AM", "AZ", "TJ", "MD"}

# Регионы, которые дополнительно проверяются при глобальном сравнении
# цен. Это НЕ весь список стран СНГ — опрашивать все 9 стран на каждое
# сообщение пользователя означало бы десятки сетевых запросов на один
# запрос в Telegram, что слишком медленно и дорого для one-shot чата.
# RU выбран как крупнейший маркетплейс-рынок СНГ, "CN" — как основной
# источник товаров напрямую от производителя, "WORLD" — как общий
# international-поиск без региональной привязки.
#
# Список легко расширить: добавление кода региона сюда сразу включает
# его в сравнение (см. `regions_to_search` ниже).
DEFAULT_CROSS_REGION_SWEEP = ("RU", "CN", "WORLD")


def regions_to_search(
    home_region: str | None,
    international: bool = True,
) -> list[str]:
    """
    Строит список регионов, которые нужно опросить для одного запроса.

    Домашний регион пользователя всегда идёт первым (там же, где он
    находится, и где лучше всего понятны местные площадки). Остальные
    регионы добавляются, только если `international` разрешает
    выходить за пределы домашнего региона (см. product_dna
    ["search_scope"]["international"]).
    """

    home_region = (home_region or "US").upper().strip()

    regions = [home_region]

    if not international:
        return regions

    for region in DEFAULT_CROSS_REGION_SWEEP:
        if region != home_region and region not in regions:
            regions.append(region)

    return regions
